#break statement in python
print("Break Statement In Python")
num = 10
while num > 0:
    print('Current Number :', num)
    num = num -1
    if num == 5:
        break
print(" ")
print("Continue Statement In Python")
Num = 15
while Num > 0:
    Num = Num -1
    if Num == 2:
        continue
    print('Current Number :', Num)
